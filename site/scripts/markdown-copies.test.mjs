import assert from "node:assert/strict";
import { cpSync, existsSync, mkdtempSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { generate } from "./generate.mjs";
import {
  SITE,
  absoluteLinks,
  llmsTxt,
  mdxToMarkdown,
  pageMarkdown,
  parseFrontmatter,
  readPages,
  siteComponents,
  slugOf,
  writeMarkdownCopies,
} from "./markdown-copies.mjs";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(site, "..");

test("reads plain, quoted, JSON and nested frontmatter", () => {
  const { data, body } = parseFrontmatter(
    '---\ntitle: How it works\ndescription: "Flag posts: spam"\nsidebar:\n  order: 1\n  label: Overview\n---\n\nBody\n',
  );
  assert.deepEqual(data, { title: "How it works", description: "Flag posts: spam", sidebar: { order: 1, label: "Overview" } });
  assert.equal(body, "\nBody\n");
  assert.deepEqual(parseFrontmatter('---\ntitle: "decide-1b"\nsidebar: {"order":3}\n---\n').data, {
    title: "decide-1b",
    sidebar: { order: 3 },
  });
});

test("slugs follow Starlight: no extension and no final index", () => {
  assert.equal(slugOf("how-it-works.mdx"), "how-it-works");
  assert.equal(slugOf("examples/index.md"), "examples");
  assert.equal(slugOf("models/decide-1b.md"), "models/decide-1b");
});

test("site links become full URLs, except in code", () => {
  const text = "[a](/gliner-runner/start/#x) [b](https://x.dev)\n```\n[c](/gliner-runner/start/)\n```";
  assert.equal(absoluteLinks(text), `[a](${SITE}/start/#x) [b](https://x.dev)\n\`\`\`\n[c](/gliner-runner/start/)\n\`\`\``);
});

test("MDX imports are dropped and components replaced by text", () => {
  const body = 'import Fig from "../Fig.astro";\n\nBefore\n\n<Fig />\n\n```js\nimport x from "y";\n<Fig />\n```\n';
  assert.equal(mdxToMarkdown(body, { Fig: () => "The figure as text.\n" }), '\nBefore\n\nThe figure as text.\n\n```js\nimport x from "y";\n<Fig />\n```\n');
  assert.throws(() => mdxToMarkdown("<Other />", {}), /no plain-text equivalent for <Other \/>/);
  assert.throws(() => mdxToMarkdown("Text <Inline /> here", {}), /cannot write a Markdown copy/);
});

test("a copy starts with the title, the description and the web page", () => {
  const page = { slug: "start", mdx: false, data: { title: "Get started", description: "Install it." }, body: "\nSee [x](/gliner-runner/models/).\n" };
  assert.equal(
    pageMarkdown(page),
    `# Get started\n\n> Install it.\n\nWeb page: ${SITE}/start/\n\nSee [x](${SITE}/models/).\n`,
  );
});

// The sidebar of astro.config.mjs in its order: links, slugs, page ids and autogenerated directories.
function sidebarEntries() {
  const config = readFileSync(join(site, "astro.config.mjs"), "utf8");
  const sidebar = config.slice(config.indexOf("sidebar: ["));
  const entries = [];
  const re = /link:\s*"\/([^"]*?)\/?"|slug:\s*"([^"]+)"|directory:\s*"([^"]+)"|"([a-z0-9-]+\/[a-z0-9-]+)"/g;
  for (const m of sidebar.matchAll(re)) entries.push(m[1] ?? m[2] ?? (m[3] ? `${m[3]}/*` : m[4]));
  return entries;
}

function buildCopies() {
  // The real pages: the hand-written ones plus the ones generate.mjs writes, in a scratch folder.
  const content = mkdtempSync(join(tmpdir(), "content-"));
  cpSync(join(site, "src/content/docs"), content, { recursive: true });
  generate(root, content);
  const out = mkdtempSync(join(tmpdir(), "public-"));
  const result = writeMarkdownCopies(content, out, siteComponents(site));
  return { content, out, result };
}

test("llms.txt links every sidebar page, in the sidebar's order, and each copy exists", () => {
  const { content, out } = buildCopies();
  const pages = readPages(content);
  const text = readFileSync(join(out, "llms.txt"), "utf8");
  assert.equal(text, llmsTxt(pages));
  assert.match(text, /^# GLiNER Runner\n\n> .+\n/);

  const links = [...text.matchAll(/^- \[[^\]]+\]\(([^)]+)\)/gm)].map((m) => m[1]);
  const slugs = links.map((url) => url.slice(SITE.length + 1).replace(/(\.md|\/)$/, ""));
  const expected = sidebarEntries().flatMap((entry) => {
    if (!entry.endsWith("/*")) return [entry];
    const dir = entry.slice(0, -2);
    const inDir = pages.filter((p) => p.slug === dir || p.slug.startsWith(`${dir}/`));
    assert.ok(inDir.length > 0, `no pages in ${dir}`);
    return slugs.filter((s) => inDir.some((p) => p.slug === s));
  });
  assert.deepEqual(slugs, expected);
  // Every docs page is linked, and every linked copy was written.
  assert.deepEqual([...slugs].filter((s) => s !== "playground" && s !== "be-the-model").sort(), pages.map((p) => p.slug).sort());
  for (const url of links.filter((u) => u.endsWith(".md"))) {
    assert.ok(existsSync(join(out, url.slice(SITE.length + 1))), url);
  }
});

test("the How it works copy writes the figure's requests and replies as text", () => {
  const { out } = buildCopies();
  const copy = readFileSync(join(out, "how-it-works.md"), "utf8");
  assert.doesNotMatch(copy, /^import /m);
  assert.doesNotMatch(copy, /<RequestAndReply/);
  assert.match(copy, /"text": "I will pay my rent on Friday, and then I will bake bread\."/);
  assert.match(copy, /"value": "money",\n\s+"confidence": 0\.7832197985980985/);
  assert.match(copy, /`"min_labels": 0` and `"max_labels": null` added to the task/);
  assert.match(copy, /^# How it works\n/);
});

test("a second run removes copies of pages that are gone", () => {
  const content = mkdtempSync(join(tmpdir(), "content-"));
  const out = mkdtempSync(join(tmpdir(), "public-"));
  mkdirSync(join(out, "runner-templates"));
  writeFileSync(join(out, "runner-templates", "template.json"), "{}");
  mkdirSync(join(out, "examples"));
  writeFileSync(join(out, "examples", "old.md"), "old");
  for (const slug of ["how-it-works", "start", "command-line-and-http", "use-in-react", "use-from-a-coding-agent", "accuracy", "evaluation", "more-ideas", "releases"]) {
    writeFileSync(join(content, `${slug}.md`), `---\ntitle: ${slug}\n---\n\nText.\n`);
  }
  mkdirSync(join(content, "examples"));
  mkdirSync(join(content, "models"));
  mkdirSync(join(content, "docs"));
  writeFileSync(join(content, "models", "index.md"), "---\ntitle: Models\n---\n");
  writeFileSync(join(content, "docs", "protocol.md"), "---\ntitle: Protocol\n---\n");
  for (const slug of ["index", "support-tickets", "text-messages", "which-language", "other-languages", "email-lines", "urgent-or-can-wait", "personal-information", "moderation", "reviews", "keep-or-discard"]) {
    writeFileSync(join(content, "examples", `${slug}.md`), `---\ntitle: ${slug}\n---\n`);
  }
  writeMarkdownCopies(content, out);
  assert.ok(!existsSync(join(out, "examples", "old.md")));
  assert.ok(existsSync(join(out, "examples", "moderation.md")));
  assert.ok(existsSync(join(out, "examples.md")));
  assert.ok(existsSync(join(out, "runner-templates", "template.json")));
});
