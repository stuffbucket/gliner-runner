/** The How it works figure (src/components/RequestAndReply.astro) as text: both requests and both replies. */
export function requestAndReplyText(figure) {
  // Indented JSON, with each list of plain values on one line.
  const json = (value) =>
    JSON.stringify(value, null, 2).replace(/\[\s*([^[\]{}]*?)\s*\]/g, (_, items) => `[${items.replace(/,\s+/g, ", ")}]`);
  const [first, ...others] = figure.replies;
  const request = (reply) => ({
    model: figure.model,
    backend: "onnx",
    precision: "fp32",
    operation: "classify",
    text: figure.text,
    schema: { kind: "classification", tasks: { [figure.task]: reply.task } },
  });
  const lines = [
    `The numbers below are from real replies of \`${figure.model}\`.`,
    "",
    "**1. You send.** The request for one label:",
    "",
    "```json",
    json(request(first)),
    "```",
    "",
  ];
  for (const reply of others) {
    const added = Object.keys(reply.task).filter((key) => !(key in first.task));
    lines.push(
      `The request for ${reply.title.toLowerCase()} is the same, with ` +
        `${added.map((key) => `\`"${key}": ${JSON.stringify(reply.task[key])}\``).join(" and ")} added to the task.`,
      "",
    );
  }
  lines.push(`**2. The model.** ${figure.model_text}`, "", "**3. You get back.** `request_id` and `_meta` are left out.", "");
  for (const reply of figure.replies) {
    const answer = {
      output: {
        [figure.task]: { value: reply.value, confidence: reply.confidence, probabilities: reply.probabilities },
      },
      timing: { queue_ms: reply.queueMs, inference_ms: reply.inferenceMs },
      usage: { inputTokens: figure.inputTokens, outputTokens: 0 },
    };
    lines.push(`**${reply.title}.** ${reply.rule}`, "", "```json", json(answer), "```", "");
  }
  lines.push(
    `\`usage\` counts ${figure.inputTokens} input tokens (the labels and the text) and 0 output tokens, because the ` +
      "model writes nothing.",
  );
  return lines.join("\n");
}

/**
 * The "Be the model" sliders (src/components/BeTheModel.jsx) as text: what they do, and for each label the text
 * the model gave the highest score for that label, with every score.
 */
export function beTheModelText(data) {
  const names = data.labels.map((label) => label.name);
  const picks = [...new Set(names.map((name) => data.examples.reduce((a, b) => (b.scores[name] > a.scores[name] ? b : a))))];
  const cell = (text) => text.replace(/\|/g, "\\|");
  const lines = [
    "On the web page this is a set of sliders, one for each label, set to the model's scores for one text. Moving " +
      "a slider shows the text whose score for that label is nearest, and the other sliders move to that text's " +
      "scores. The scores always add up to 1, so more on one leaves less for the rest.",
    "",
    `${data.mock ? "These scores are made up." : `The scores are from \`${data.model}\`, picking one label.`} ` +
      "The text with the highest score for each label:",
    "",
    `| Text | ${names.map(cell).join(" | ")} |`,
    `| --- | ${names.map(() => "---:").join(" | ")} |`,
    ...picks.map((example) => `| ${cell(example.text)} | ${names.map((name) => example.scores[name].toFixed(3)).join(" | ")} |`),
  ];
  return lines.join("\n");
}

export function siteComponents(siteDir) {
  const figure = JSON.parse(readFileSync(join(siteDir, "src/data/request-and-reply.json"), "utf8"));
  return {
    RequestAndReply: () => requestAndReplyText(figure),
    // Ready for when How it works shows the sliders; no page uses it yet.
    BeTheModel: () => beTheModelText(beTheModelData(siteDir)),
  };
}
