/** Reads the frontmatter fields the copies use: plain, quoted or JSON values, and one level of nesting. */
export function parseFrontmatter(source) {
  const m = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { data: {}, body: source };
  const value = (raw) => {
    const v = raw.trim();
    if (v === "") return undefined;
    if (/^["{[]/.test(v) || /^-?\d+(\.\d+)?$/.test(v) || v === "true" || v === "false" || v === "null") {
      try {
        return JSON.parse(v);
      } catch {
        // not JSON; fall through to a plain string
      }
    }
    if (v.startsWith("'") && v.endsWith("'")) return v.slice(1, -1).replaceAll("''", "'");
    return v;
  };
  const data = {};
  let parent;
  for (const line of m[1].split(/\r?\n/)) {
    const top = line.match(/^([A-Za-z_][\w-]*):(.*)$/);
    const nested = line.match(/^\s+([A-Za-z_][\w-]*):(.*)$/);
    if (top) {
      const v = value(top[2]);
      parent = v === undefined ? top[1] : undefined;
      data[top[1]] = v === undefined ? {} : v;
    } else if (nested && parent) {
      data[parent][nested[1]] = value(nested[2]);
    }
  }
  return { data, body: source.slice(m[0].length) };
}

/** The Starlight slug of a content file: its path without the extension and without a final `index`. */
export function slugOf(relPath) {
  return relPath
    .split(sep)
    .join("/")
    .replace(/\.mdx?$/, "")
    .replace(/(^|\/)index$/, "")
    .toLowerCase();
}

export function readPages(contentDir) {
  const pages = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const file = join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (/\.mdx?$/.test(entry.name)) {
        const source = readFileSync(file, "utf8");
        const { data, body } = parseFrontmatter(source);
        pages.push({ slug: slugOf(relative(contentDir, file)), mdx: entry.name.endsWith(".mdx"), data, body });
      }
    }
  };
  walk(contentDir);
  return pages.sort((a, b) => a.slug.localeCompare(b.slug));
}

// ---------------------------------------------------------------- the copies

export const pageUrl = (slug) => `${SITE}/${slug}/`;
export const copyUrl = (slug) => `${SITE}/${slug}.md`;
export const copyPath = (slug) => `${slug}.md`;

/** Applies `fn` to every line outside fenced code blocks. */
function outsideFences(markdown, fn) {
  let fence = null;
  return markdown
    .split("\n")
    .map((line) => {
      const open = line.match(/^\s*(`{3,}|~{3,})/);
      if (open && (fence === null || open[1].startsWith(fence))) {
        fence = fence === null ? open[1] : null;
        return line;
      }
      return fence === null ? fn(line) : line;
    })
    .filter((line) => line !== null)
    .join("\n");
}

/** Site links (`/gliner-runner/...`) become full URLs, so a copy read on its own still points at the site. */
export function absoluteLinks(markdown) {
  return outsideFences(markdown, (line) =>
    line.replace(/\]\(\/gliner-runner\/([^)\s]*)/g, (_, rest) => `](${SITE}/${rest}`),
  );
}

/** Drops MDX imports and replaces each `<Component />` line with its plain-text equivalent. */
export function mdxToMarkdown(body, components) {
  return outsideFences(body, (line) => {
    if (/^import\s.+\sfrom\s+["'][^"']+["'];?\s*$/.test(line)) return null;
    const tag = line.match(/^\s*<([A-Z]\w*)(\s[^>]*)?\/>\s*$/);
    if (tag) {
      const render = components[tag[1]];
      if (!render) throw new Error(`no plain-text equivalent for <${tag[1]} /> (add one to the components map)`);
      return render().trim();
    }
    if (/<[A-Z]\w*[\s/>]/.test(line.replace(/`[^`]*`/g, ""))) {
      throw new Error(`cannot write a Markdown copy of this MDX line: ${line.trim()}`);
    }
    return line;
  });
}

export function pageMarkdown(page, components = {}) {
  const body = page.mdx ? mdxToMarkdown(page.body, components) : page.body;
  const head = [`# ${page.data.title}`, ""];
  if (page.data.description) head.push(`> ${page.data.description}`, "");
  head.push(`Web page: ${pageUrl(page.slug)}`, "");
  return `${head.join("\n")}\n${absoluteLinks(body).replace(/^\s*\n/, "").replace(/\n*$/, "\n")}`;
}

// ---------------------------------------------------------------- llms.txt

const sidebarOrder = (page) => page.data.sidebar?.order ?? Number.POSITIVE_INFINITY;

/** The slugs of one section entry: a page, or every page of an autogenerated directory in Starlight's order. */
export function expandEntry(entry, pages) {
  if (!entry.endsWith("/*")) return [entry];
  const dir = entry.slice(0, -1);
  return pages
    .filter((p) => p.slug.startsWith(dir) || p.slug === dir.slice(0, -1))
    .sort((a, b) => sidebarOrder(a) - sidebarOrder(b) || a.slug.localeCompare(b.slug))
    .map((p) => p.slug);
}

export function llmsTxt(pages, sections = SECTIONS) {
  const bySlug = new Map(pages.map((p) => [p.slug, p]));
  const lines = ["# GLiNER Runner", "", `> ${SUMMARY}`, "", DETAILS, ""];
  for (const section of sections) {
    lines.push(`## ${section.title}`, "");
    for (const slug of section.pages.flatMap((entry) => expandEntry(entry, pages))) {
      const page = bySlug.get(slug);
      const other = OTHER_PAGES[slug];
      if (!page && !other) throw new Error(`llms.txt: no page for ${slug}`);
      const { title, description } = page ? page.data : other;
      const url = page ? copyUrl(slug) : pageUrl(slug);
      lines.push(`- [${title}](${url})${description ? `: ${description}` : ""}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

// ---------------------------------------------------------------- writing

/** Removes the copies and llms.txt a previous run wrote: every .md file under `publicDir`, and emptied folders. */
function clean(publicDir) {
  rmSync(join(publicDir, "llms.txt"), { force: true });
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const file = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(file);
        if (readdirSync(file).length === 0) rmdirSync(file);
      } else if (entry.name.endsWith(".md")) {
        rmSync(file);
      }
    }
  };
  if (existsSync(publicDir)) walk(publicDir);
}

export function writeMarkdownCopies(contentDir, publicDir, components = {}) {
  const pages = readPages(contentDir);
  const text = llmsTxt(pages);
  const copies = pages.map((page) => [copyPath(page.slug), pageMarkdown(page, components)]);
  clean(publicDir);
  for (const [rel, markdown] of copies) {
    const file = join(publicDir, rel);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, markdown);
  }
  writeFileSync(join(publicDir, "llms.txt"), text);
  return { pages: copies.length };
}

