// Writes a Markdown copy of every docs page and an llms.txt (https://llmstxt.org/) that links them, for people and
// agents that read Markdown. generate.mjs runs it after the generated pages exist. The files go to public/, which
// Astro copies into the build as they are:
//
//   src/content/docs/how-it-works.mdx     -> public/how-it-works.md     -> /gliner-runner/how-it-works.md
//   src/content/docs/examples/index.md    -> public/examples.md         -> /gliner-runner/examples.md
//   src/content/docs/models/decide-1b.md  -> public/models/decide-1b.md -> /gliner-runner/models/decide-1b.md
//
// A copy is the page's title, description and Markdown body. Site links become full URLs. In an .mdx page the
// imports are dropped and each component is replaced by the plain text its entry in `components` returns; an
// unknown component is an error, so a new one cannot slip into the copies unseen.

